%include "kernel/machine/branch.inc"
section .text
%ifidn __OUTPUT_FORMAT__,macho64
%define C(x) _ %+ x
%else
%define C(x) x
%endif
extern C(machine_headers_valid), C(machine_http_responses)
global C(machine_http_select)
%macro J 2
 MACHINE_REL8 %1,%2
%endmacro
%macro N 2
 db 0x0f,%1
 dd %2-($+4)
%endmacro
%ifdef GUEST_EXPORTS
global http_select
http_select:
%endif
C(machine_http_select):
 db 0x48,0x81,0xfe
 dd 768 ; cmp rsi,768
 J 0x76,bounded
 db 0xb8
 dd -1
 db 0xc3
bounded:
 db 0x31,0xc0 ; eax=end=0
 db 0x48,0x83,0xfe,4
 J 0x72,incomplete
 db 0x48,0x83,0xee,4 ; last possible separator offset
scan:
 db 0x81,0x3c,0x07
 dd 0x0a0d0a0d ; cmp dword [rdi+rax], CRLFCRLF
 J 0x74,complete
 db 0x48,0xff,0xc0,0x48,0x39,0xf0
 J 0x76,scan
incomplete:
 db 0x31,0xc0,0xc3
complete:
 ; Five saved registers align the C call.
 db 0x53,0x55,0x41,0x54,0x41,0x55,0x41,0x56
 db 0x48,0x89,0xfb,0x49,0x89,0xd4 ; rbx=p; r12=out
 db 0x31,0xed ; response index invalid
 db 0x48,0x39,0xf0 ; separator must be exactly n-4
 N 0x85,selected
 db 0x49,0x89,0xc5 ; r13=end
 db 0x45,0x31,0xf6 ; r14=line=0
line_scan:
 db 0x66,0x42,0x81,0x3c,0x33
 dw 0x0a0d ; [rbx+r14] CRLF; end itself guarantees bounded terminator
 J 0x74,line_found
 db 0x49,0xff,0xc6
 J 0xeb,line_scan
line_found:
 db 0x31,0xc0 ; a=0
first_space:
 db 0x4c,0x39,0xf0 ; cmp rax,r14
 N 0x83,invalid
 db 0x80,0x3c,0x03,32
 J 0x74,first_found
 db 0x48,0xff,0xc0
 J 0xeb,first_space
first_found:
 db 0x48,0x85,0xc0
 J 0x74,invalid
 db 0x48,0x8d,0x48,1 ; b=a+1
second_space:
 db 0x4c,0x39,0xf1 ; cmp rcx,r14
 J 0x73,invalid
 db 0x80,0x3c,0x0b,32
 J 0x74,second_found
 db 0x48,0xff,0xc1
 J 0xeb,second_space
second_found:
 db 0x80,0x7c,0x03,1,0x2f ; target starts slash
 J 0x75,invalid
 db 0x4c,0x89,0xf2,0x48,0x29,0xca ; edx=line-b
 db 0x83,0xfa,9
 J 0x75,invalid
 db 0x81,0x7c,0x0b,1
 dd 0x50545448 ; HTTP
 J 0x75,invalid
 db 0x81,0x7c,0x0b,4
 dd 0x2e312f50 ; P/1.
 J 0x75,invalid
 db 0x0f,0xb6,0x54,0x0b,8 ; final version character
 db 0x83,0xea,0x30,0x83,0xfa,1
 J 0x77,invalid
 db 0x89,0xd7 ; edi=http11 (temporarily)
 db 0xbd
 dd 1 ; method response
 db 0x83,0xf8,3
 J 0x75,validate
 db 0x81,0x3b
 dd 0x20544547 ; GET plus actual first space
 J 0x75,validate
 db 0xbd
 dd 2 ; missing response
 db 0x48,0x29,0xc1 ; target + preceding space width = b-a
 db 0x83,0xf9,2
 J 0x75,validate
 db 0xff,0xc5 ; page index3
validate:
 db 0x89,0xf9,0x48,0x89,0xdf ; ecx=http11; rdi=p
 db 0x4c,0x89,0xf6,0x4c,0x89,0xea ; rsi=line; rdx=end
 db 0xe8
 dd C(machine_headers_valid)-($+4)
 db 0x84,0xc0
 J 0x75,selected
invalid:
 db 0x31,0xed
selected:
 db 0x48,0x8d,0x05
 dd C(machine_http_responses)-($+4)
 db 0xc1,0xe5,4,0x48,0x01,0xe8 ; response table index *16
 db 0x48,0x8b,0x10,0x49,0x89,0x14,0x24
 db 0x48,0x8b,0x50,8,0x49,0x89,0x54,0x24,8
 db 0xb8
 dd 1
 db 0x41,0x5e,0x41,0x5d,0x41,0x5c,0x5d,0x5b,0xc3
MACHINE_BRANCH_FINISH

C(machine_checksum):
    db 0x31,0xc0 ; xor eax,eax
sum:
    db 0x48,0x83,0xfe,0x20 ; cmp rsi,32
    MACHINE_REL8 0x72, eight ; jb eight
.blocks:
    db 0x48,0x03,0x07,0x48,0x83,0xd0,0x00 ; add rax,[rdi] / adc rax,0
    db 0x48,0x03,0x47,0x08,0x48,0x83,0xd0,0x00 ; add rax,[rdi+8] / adc rax,0
    db 0x48,0x03,0x47,0x10,0x48,0x83,0xd0,0x00 ; add rax,[rdi+16] / adc rax,0
    db 0x48,0x03,0x47,0x18,0x48,0x83,0xd0,0x00 ; add rax,[rdi+24] / adc rax,0
    db 0x48,0x83,0xc7,0x20 ; add rdi,32
    db 0x48,0x83,0xee,0x20 ; sub rsi,32
    db 0x48,0x83,0xfe,0x20 ; cmp rsi,32
    MACHINE_REL8 0x73, .blocks ; jae blocks
eight:
    db 0x48,0x83,0xfe,0x08 ; cmp rsi,8
    MACHINE_REL8 0x72, tail ; jb tail
.words:
    db 0x48,0x03,0x07 ; add rax,[rdi]
    db 0x48,0x83,0xd0,0x00 ; adc rax,0 (end-around carry)
    db 0x48,0x83,0xc7,0x08 ; add rdi,8
    db 0x48,0x83,0xee,0x08 ; sub rsi,8
    db 0x48,0x83,0xfe,0x08 ; cmp rsi,8
    MACHINE_REL8 0x73, .words ; jae words
 tail:
    db 0x48,0x83,0xfe,0x02 ; cmp rsi,2
    MACHINE_REL8 0x72, odd ; jb odd
.pairs:
    db 0x0f,0xb7,0x17 ; movzx edx,word [rdi]
    db 0x48,0x01,0xd0 ; add rax,rdx
    db 0x48,0x83,0xd0,0x00 ; adc rax,0
    db 0x48,0x83,0xc7,0x02 ; add rdi,2
    db 0x48,0x83,0xee,0x02 ; sub rsi,2
    db 0x48,0x83,0xfe,0x02 ; cmp rsi,2
    MACHINE_REL8 0x73, .pairs ; jae pairs
odd:
    db 0x48,0x85,0xf6 ; test rsi,rsi
    MACHINE_REL8 0x74, fold ; jz fold
    db 0x0f,0xb6,0x17 ; movzx edx,byte [rdi]
    db 0x48,0x01,0xd0 ; add rax,rdx
    db 0x48,0x83,0xd0,0x00 ; adc rax,0
fold:
    db 0x48,0x89,0xc2 ; mov rdx,rax
    db 0x48,0xc1,0xea,0x20 ; shr rdx,32
    db 0x01,0xd0 ; add eax,edx
    db 0x83,0xd0,0x00 ; adc eax,0
    db 0x89,0xc2 ; mov edx,eax
    db 0xc1,0xea,0x10 ; shr edx,16
    db 0x66,0x01,0xd0 ; add ax,dx
    db 0x66,0x83,0xd0,0x00 ; adc ax,0
    db 0x66,0xc1,0xc0,0x08 ; rol ax,8
    db 0x66,0xf7,0xd0 ; not ax
    db 0x0f,0xb7,0xc0 ; movzx eax,ax
    db 0xc3 ; ret
